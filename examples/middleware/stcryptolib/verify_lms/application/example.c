/** ########## Step 1 ##########
  * Demonstrates how to use the STM32 Cryptographic library to verify a message
  * authenticity and integrity with a known signature, using the LMS algorithm
  * (Leighton-Micali Signatures, a stateful hash-based signature scheme) with
  * SHA-256.
  *
  * This step is scheduled as follows:
  * Step 1.1: Constructs the HBS context
  * Step 1.2: Verifies the message signature (with fault-injection protection check)
  *
  */
app_status_t app_process(void)
{
  app_status_t return_status = EXEC_STATUS_ERROR;
  cmox_hbs_retval_t retval;
  /* Fault check verification variable */
  uint32_t fault_check = CMOX_HBS_AUTH_FAIL;

  /** ########## Step 1.1 ##########
    * Constructs the HBS context
    */
  /**
    * Construct a HBS context, specifying mathematics implementation and working buffer for later processing
    */
  cmox_hbs_construct(&Hbs_Ctx, CMOX_HBS_SHA256);
  PRINTF("[INFO] Step 1.1: Construct the HBS context COMPLETED.\n");

  /** ########## Step 1.2 ##########
    * Verifies the message signature (with fault-injection protection check)
    */
  /* Verify the signature passing all the needed parameters */
  retval = cmox_hbs_verify(&Hbs_Ctx,
                           CMOX_LMS_VERIFY_M32, /* Use LMS verify algorithm */
                           Public_Key, sizeof(Public_Key), /* Public Key to verify the signature */
                           Message, sizeof(Message), /* Message buffer */
                           Known_Signature, sizeof(Known_Signature), /* Signature to be verified */
                           &fault_check); /* Fault check variable:
                                             to ensure no fault injection occurs during this API call */

  /* Verify API returned value */
  if (retval != CMOX_HBS_AUTH_SUCCESS)
  {
    PRINTF("[ERROR] Step 1.2: Verify the signature ERROR.\n");
    goto _app_process_exit;
  }

  /* Verify Fault check variable value */
  if (fault_check != CMOX_HBS_AUTH_SUCCESS)
  {
    PRINTF("[ERROR] Step 1.2: Signature fault-injection check ERROR.\n");
    goto _app_process_exit;
  }
  PRINTF("[INFO] Step 1.2: Verify the signature COMPLETED.\n");

  return_status = EXEC_STATUS_OK;

_app_process_exit:
  return return_status;
} /* end app_process */


